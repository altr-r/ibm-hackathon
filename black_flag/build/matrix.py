"""
build/matrix.py — Run the 3×3 (distro × stage) Docker build/test matrix.

The matrix is sequenced intentionally:

    For each distro in targets:
        PREPARE   (install OS deps + run adapted setup.sh)
        BUILD     (pip install requirements)
        TEST      (run application's test.sh)

Stages short-circuit: if PREPARE fails we don't waste time running BUILD or
TEST for that distro — they would inherit the same broken state and produce
noisy, uninformative output.  Skipped stages return exit_code = -1 so the
CLI's matrix display can render them as an em-dash (—) instead of a spurious
red ❌.

After every individual stage, *progress_cb* is called with the resulting
:class:`StageResult` so the CLI can print live progress without waiting for
the full matrix.
"""
from __future__ import annotations

from pathlib import Path
from typing import Callable

from black_flag.core.types import BuildMatrix, Stage, StageResult, TargetResult
from black_flag.runtime.detector import adapter_for_distro
from .container import run_distro_stages


# Stages execute in this fixed order per distro.
_STAGE_ORDER: list[Stage] = ["prepare", "build", "test"]


def run_matrix(
    *,
    working_tree: Path,
    targets: list[str],
    iteration: int = 0,
    progress_cb: Callable[[StageResult], None] | None = None,
) -> BuildMatrix:
    """
    Run the full build / test matrix.

    Parameters
    ----------
    working_tree:
        Absolute path to the (adapted) application directory.  ``bf_scripts``
        must already exist inside (generated by ``generate_scripts``).
    targets:
        Subset of ``["ubuntu", "fedora", "arch"]`` — distros to actually run.
        The caller may drop a distro from the list on a repair loop iteration
        when it has been marked UNSUPPORTED.
    iteration:
        Which repair-loop iteration this matrix run is for (0-based).  Only
        stored on the returned ``BuildMatrix`` for debugging / display.
    progress_cb:
        Optional ``Callable[[StageResult], None]`` invoked immediately after
        each individual stage completes.  The CLI uses this to stream
        per-stage ❌ / ✅ indicators while the matrix is in progress.

    Returns
    -------
    BuildMatrix
        Aggregated results.  ``matrix.results`` contains ``StageResult``
        objects in the exact order they were executed.
    """
    results: list[StageResult] = []

    for distro in targets:
        adapter = adapter_for_distro(distro)
        if adapter is None:
            # Unknown distro — mark all stages as a failed PREPARE so the
            # caller surfaces the error rather than crashing here.
            fail = StageResult(
                distro=distro,
                stage="prepare",
                exit_code=1,
                stdout="",
                stderr=f"[black-flag] unknown distro id: {distro!r}",
                elapsed_s=0.0,
            )
            results.append(fail)
            if progress_cb:
                progress_cb(fail)
            for skipped_stage in ("build", "test"):
                skip = StageResult(
                    distro=distro,
                    stage=skipped_stage,
                    exit_code=-1,
                    stdout="",
                    stderr=f"[black-flag] skipped ({distro}/prepare failed)",
                    elapsed_s=0.0,
                )
                results.append(skip)
                if progress_cb:
                    progress_cb(skip)
            continue

        env = adapter.environment_configuration()

        prepare_sr, build_sr, test_sr = run_distro_stages(
            working_tree=working_tree,
            distro_id=distro,
            docker_image=adapter.docker_image,
            env=env,
        )
        for sr in (prepare_sr, build_sr, test_sr):
            results.append(sr)
            if progress_cb:
                progress_cb(sr)

    return BuildMatrix(results=results, iteration=iteration)


def matrix_to_target_results(
    matrix: BuildMatrix,
    targets: list[str],
) -> dict[str, TargetResult]:
    """
    Convert a :class:`BuildMatrix` into the per-distro ``TargetResult`` map
    stored in the compatibility manifest.

    A distro is ``COMPATIBLE`` only when all three stages exit 0.  Any
    non-zero exit code in any stage produces ``FAILED``.  If the caller
    passed a distro that never appears in the matrix it is reported as
    ``UNVERIFIED``.
    """
    target_results: dict[str, TargetResult] = {}

    for distro in targets:
        distro_results = [r for r in matrix.results if r.distro == distro]
        if not distro_results:
            target_results[distro] = TargetResult(status="UNVERIFIED")
            continue

        by_stage: dict[str, StageResult] = {r.stage: r for r in distro_results}
        prepare_r = by_stage.get("prepare")
        build_r = by_stage.get("build")
        test_r = by_stage.get("test")

        prepare_ok = prepare_r is not None and prepare_r.exit_code == 0
        build_ok = build_r is not None and build_r.exit_code == 0
        test_ok = test_r is not None and test_r.exit_code == 0

        # Treat skipped stages (exit_code == -1) as "not run" rather than pass/fail
        all_run = all(
            r is not None and r.exit_code != -1 for r in (prepare_r, build_r, test_r)
        )
        all_ok = prepare_ok and build_ok and test_ok

        if all_run and all_ok:
            status = "COMPATIBLE"
        elif any(
            r is not None and r.exit_code != 0 and r.exit_code != -1
            for r in (prepare_r, build_r, test_r)
        ):
            status = "FAILED"
        else:
            status = "UNVERIFIED"

        target_results[distro] = TargetResult(
            status=status,
            prepare=prepare_ok if prepare_r and prepare_r.exit_code != -1 else None,
            build=build_ok if build_r and build_r.exit_code != -1 else None,
            test=test_ok if test_r and test_r.exit_code != -1 else None,
        )

    return target_results
